/**
 * Dart config writer for Auth0 Flutter Windows Desktop.
 *
 * Writes Auth0 credentials to lib/auth0_config.dart.
 * Flutter Windows uses Dart constants rather than a native config file
 * (no Info.plist or strings.xml equivalent on Windows Desktop).
 */

import fs from "fs"
import path from "path"
import ora from "ora"

/**
 * Write Auth0 credentials to lib/auth0_config.dart.
 *
 * @param {{ projectPath: string, domain: string, clientId: string, customScheme?: string }} opts
 */
export async function writeDartConfig({ projectPath, domain, clientId, customScheme = "myapp" }) {
  const spinner = ora("Writing lib/auth0_config.dart").start()

  const libDir = path.join(projectPath, "lib")
  if (!fs.existsSync(libDir)) {
    fs.mkdirSync(libDir, { recursive: true })
  }

  const configPath = path.join(libDir, "auth0_config.dart")

  const content = `// Auth0 credentials for Flutter Windows Desktop
// Generated by auth0-flutter-windows bootstrap script.
// Safe to commit — Native apps do not use ClientSecret.
const String auth0Domain = '${domain}';
const String auth0ClientId = '${clientId}';

// Custom URL scheme used as the Windows protocol handler.
// Must match:
//   - The protocol registered in the Windows Registry
//   - The Allowed Callback / Logout URLs in the Auth0 Dashboard
//   - The appCustomURL passed to windowsWebAuthentication().login()
const String auth0CustomScheme = '${customScheme}';
`

  fs.writeFileSync(configPath, content, "utf-8")
  spinner.succeed(`Written: lib/auth0_config.dart`)
}
